/** Exact light/dark pairs consumed by the official theme override service. */
export const themeOverrides: Record<string, ColorPair> = Object.fromEntries(
  Object.entries(bindings).map(([token, role]) => [token, { ...colors[role] }]),
);

/** Resolved mode values shared with the standalone design preview. */
export const palettes: Record<ThemeMode, Record<string, string>> = {
  light: Object.fromEntries(Object.entries(themeOverrides).map(([name, value]) => [name, value.light])),
  dark: Object.fromEntries(Object.entries(themeOverrides).map(([name, value]) => [name, value.dark])),
};
